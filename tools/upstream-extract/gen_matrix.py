#!/usr/bin/env python3
"""Generate docs/parity-matrix.md from the extracted contracts and the classification.

Fails if any upstream tool is unclassified or the classification names a tool
upstream does not have. Standard library only.

Usage:
    python3 gen_matrix.py [--root .]
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

ACCESS = ("READ", "OPERATE", "ADMIN")
STATUSES = ("not-started", "in-progress", "done", "excluded")

# Non-tool upstream features and how the Java port handles them.
FEATURES = [
    ("Streamable HTTP transport", "`MCP_TRANSPORT=http`", "Ported", "Stateless mode"),
    ("stdio transport", "`MCP_TRANSPORT=stdio` (upstream default)", "Ported", "Java default is `http`"),
    ("SSE transport", "`MCP_TRANSPORT=sse`", "Excluded", "Deprecated in MCP spec; approved 2026-10-24"),
    ("Static bearer token", "`MCP_HTTP_BEARER_TOKEN`", "Ported", "Becomes API-key fallback with configurable role"),
    ("Entra ID OAuth", "-", "New", "Java-only"),
    ("Read-only mode", "`READ_ONLY_MODE` (default false)", "Ported", "Java default true; overrides all roles"),
    ("Disabled tags", "`DISABLED_TAGS`", "Ported", "Upstream tags preserved on every tool"),
    ("Rate limiting", "`RATE_LIMIT_*` (global sliding window)", "Ported", "Java limits per principal"),
    ("Tool search", "`TOOL_SEARCH_*` (bm25 / regex)", "Ported", "`call_tool` re-runs authorization"),
    ("Health endpoint", "`/health`, no auth, no LibreNMS call", "Ported", "Java adds `/readyz`"),
    ("Sentry", "`SENTRY_*`", "Excluded", "Not needed; approved 2026-10-24"),
]


def render_op(op: dict) -> str:
    parts = []
    for seg in op["segments"]:
        if seg[:1] in "'\"" and seg[-1:] == seg[:1]:
            parts.append(seg[1:-1])
        else:
            parts.append("{" + seg + "}")
    text = f"{op['method']} /{'/'.join(parts)}"
    if op.get("binary"):
        text += " (image)"
    return f"`{text}`"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=Path("."))
    args = parser.parse_args()

    upstream = json.loads((args.root / "contracts/upstream-tools.json").read_text())
    classification = json.loads((args.root / "contracts/tool-classification.json").read_text())["tools"]

    tools = {t["name"]: t for t in upstream["tools"]}
    errors = [f"unclassified tool: {n}" for n in tools if n not in classification]
    errors += [f"classified tool not upstream: {n}" for n in classification if n not in tools]
    for name, c in classification.items():
        if c.get("access") not in ACCESS:
            errors.append(f"{name}: access must be one of {ACCESS}")
        if c.get("javaStatus") not in STATUSES:
            errors.append(f"{name}: javaStatus must be one of {STATUSES}")
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1

    meta = upstream["upstream"]
    access_counts = Counter(c["access"] for c in classification.values())
    status_counts = Counter(c["javaStatus"] for c in classification.values())
    by_module = defaultdict(list)
    for t in upstream["tools"]:
        by_module[t["module"]].append(t)

    out = [
        "# Feature Parity Matrix",
        "",
        "<!-- Generated by tools/upstream-extract/gen_matrix.py. Do not edit by hand:",
        "     change contracts/tool-classification.json and regenerate. -->",
        "",
        f"**Upstream:** {meta['repository']} @ `{meta['commit']}` "
        f"(v{meta['packageVersion']}, FastMCP {meta['fastmcpVersion']})",
        "",
        f"**Tools:** {len(tools)} — "
        + ", ".join(f"{k} {access_counts[k]}" for k in ACCESS)
        + f"; destructive {sum(c['destructive'] for c in classification.values())}",
        "",
        "**Java status:** " + ", ".join(f"{s} {status_counts[s]}" for s in STATUSES),
        "",
        "## Legend",
        "",
        "- **Access**: minimum role. READ = `LibreNMS.Reader`, OPERATE = `LibreNMS.Operator`, "
        "ADMIN = `LibreNMS.Admin`. Read-only mode blocks everything above READ.",
        "- **Destr.**: destructive; also requires `ALLOW_DESTRUCTIVE=true`.",
        "- **Retry**: safe for the client to retry automatically.",
        "- **Upstream tag**: upstream's `read-only` / `admin` tag, or `untagged`.",
        "",
        "## Non-tool features",
        "",
        "| Feature | Upstream | Java | Notes |",
        "|---|---|---|---|",
    ]
    out += [f"| {f} | {u} | {j} | {n} |" for f, u, j, n in FEATURES]

    for module in sorted(by_module):
        out += [
            "",
            f"## {module}",
            "",
            "| Tool | LibreNMS operations | Upstream tag | Access | Destr. | Retry | Java | Notes |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for t in by_module[module]:
            c = classification[t["name"]]
            tag = "read-only" if "read-only" in t["tags"] else "admin" if "admin" in t["tags"] else "untagged"
            ops = "<br>".join(dict.fromkeys(render_op(o) for o in t["httpOperations"]))
            if t["helpers"]:
                ops += "<br>helpers: " + ", ".join(t["helpers"])
            out.append(
                f"| `{t['name']}` | {ops} | {tag} | {c['access']} | "
                f"{'yes' if c['destructive'] else ''} | {'yes' if c['retrySafe'] else 'no'} | "
                f"{c['javaStatus']} | {'; '.join(c['notes'])} |"
            )

    target = args.root / "docs/parity-matrix.md"
    target.write_text("\n".join(out) + "\n")
    print(f"wrote {target} ({len(tools)} tools)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
