#!/usr/bin/env python3
"""Generate docs/tool-reference.md from the tool contracts and classification.

Standard library only.

Usage:
    python3 gen_reference.py [--root .]
"""

from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path

ROLE = {"READ": "Reader", "OPERATE": "Operator", "ADMIN": "Admin"}


def type_of(schema: dict) -> str:
    if "anyOf" in schema:
        kinds = [type_of(s) for s in schema["anyOf"] if s.get("type") != "null"]
        optional = any(s.get("type") == "null" for s in schema["anyOf"])
        return " \\| ".join(kinds) + ("?" if optional else "")
    if "enum" in schema:
        return " \\| ".join(f"`{v}`" for v in schema["enum"])
    t = schema.get("type", "any")
    if t == "array":
        return type_of(schema.get("items", {})) + "[]"
    return t


def first_line(text: str | None) -> str:
    if not text:
        return ""
    line = text.strip().split("\n\n")[0].replace("\n", " ").strip()
    return line.replace("|", "\\|")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=Path("."))
    args = parser.parse_args()
    tools = json.loads((args.root / "contracts/upstream-tools.json").read_text())["tools"]
    cls = json.loads((args.root / "contracts/tool-classification.json").read_text())["tools"]

    by_module = defaultdict(list)
    for t in tools:
        by_module[t["module"]].append(t)

    out = [
        "# Tool Reference",
        "",
        "<!-- Generated by tools/upstream-extract/gen_reference.py from contracts/. Do not edit by hand. -->",
        "",
        "Every tool, the minimum role that may call it, and its parameters. Descriptions are upstream's,",
        "verbatim (the full text is what MCP clients see). **Destructive** tools also need",
        "`ALLOW_DESTRUCTIVE=true`; with `READ_ONLY_MODE=true` (the default) only Reader tools are served.",
        "",
        "| Module | Tools |",
        "|---|---|",
    ]
    out += [f"| [{m}](#{m}) | {len(ts)} |" for m, ts in sorted(by_module.items())]
    for module in sorted(by_module):
        out += ["", f"## {module}"]
        for t in by_module[module]:
            c = cls[t["name"]]
            flags = [f"**{ROLE[c['access']]}**"]
            if c["destructive"]:
                flags.append("**destructive**")
            if not t.get("outputSchema"):
                flags.append("returns an image")
            out += ["", f"### `{t['name']}`", "", " · ".join(flags), "", first_line(t["description"])]
            props = t["inputSchema"].get("properties", {})
            if props:
                required = set(t["inputSchema"].get("required", []))
                out += ["", "| Parameter | Type | Required | Default | Description |", "|---|---|---|---|---|"]
                for name, p in props.items():
                    default = f"`{json.dumps(p['default'])}`" if "default" in p and p["default"] is not None else ""
                    out.append(f"| `{name}` | {type_of(p)} | {'yes' if name in required else ''} | {default} "
                               f"| {first_line(p.get('description'))} |")
    target = args.root / "docs/tool-reference.md"
    target.write_text("\n".join(out) + "\n")
    print(f"wrote {target} ({len(tools)} tools)")


if __name__ == "__main__":
    main()
